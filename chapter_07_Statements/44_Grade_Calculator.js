//Grade Calculator with example...
let mark = 35;
if (mark >= 90) {
    console.log('Grade A');
} else if (mark >= 80 && mark <= 89) {
    console.log('Grade B');
} else if (mark >= 70 && mark <= 79) {
    console.log('Grade C');
} else if (mark >= 60 && mark <= 69) {
    console.log('Grade D');
} else {
    console.log('Mark is below 60 -Fail');
}