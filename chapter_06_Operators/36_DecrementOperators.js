//Decrement operators further divided two types: pre decrement & post  decrement.
//pre-decrement : 1st decrement happen then assign  values.
let l = 10;
let m = --l;
console.log(m); //9
console.log(l);//9

//post-decrement : 1st   assign values then decrement happened..
let e = 15;
let f = e--;
console.log(f);//15
console.log(e);//14