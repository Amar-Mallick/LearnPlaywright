/*Generally Compound perators(Shorthand operators)'s comes under Assignment operators.
It's combine(compound) two separate steps in to a single operators .*/
let value = 5;
console.log(value += 2);//5+2=7
console.log(value -= 2);//7-2=5
console.log(value *= 2);//5*2=10
console.log(value /= 2);//10/2=5
console.log(value %= 2);//5%2=1